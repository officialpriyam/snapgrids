_cached_lab = None

def _rgb_to_lab(rgb):
    r, g, b = rgb
    r = r / 255.0
    g = g / 255.0
    b = b / 255.0
    r = r / 12.92 if r <= 0.04045 else ((r + 0.055) / 1.055) ** 2.4
    g = g / 12.92 if g <= 0.04045 else ((g + 0.055) / 1.055) ** 2.4
    b = b / 12.92 if b <= 0.04045 else ((b + 0.055) / 1.055) ** 2.4
    x = (r * 0.4124564 + g * 0.3575761 + b * 0.1804375) / 0.95047
    y = (r * 0.2126729 + g * 0.7151522 + b * 0.0721750) / 1.00000
    z = (r * 0.0193339 + g * 0.1191920 + b * 0.9503041) / 1.08883
    f = lambda t: t ** (1/3) if t > 0.008856 else (7.787 * t) + (16/116)
    L = 116 * f(y) - 16
    a = 500 * (f(x) - f(y))
    b2 = 200 * (f(y) - f(z))
    return (L, a, b2)


def get_lab_palette():
    global _cached_lab
    if _cached_lab is not None:
        return _cached_lab
    _cached_lab = {}
    for block_id, rgb in BLOCK_PALETTE.items():
        if block_id == 'minecraft:air':
            continue
        _cached_lab[block_id] = _rgb_to_lab(rgb)
    return _cached_lab


def find_closest_block(rgb_color):
    if rgb_color[3] < 128:
        return 'minecraft:air'
    lab_palette = get_lab_palette()
    target_lab = _rgb_to_lab(rgb_color[:3])
    best_block = 'minecraft:stone'
    best_dist = float('inf')
    for block_id, block_lab in lab_palette.items():
        d = (target_lab[0] - block_lab[0]) ** 2 + (target_lab[1] - block_lab[1]) ** 2 + (target_lab[2] - block_lab[2]) ** 2
        if d < best_dist:
            best_dist = d
            best_block = block_id
    return best_block


